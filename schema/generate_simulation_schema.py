"""Generate the modern LinkML simulation view from the Python provisioner.

Run from the repository root: python -m schema.generate_simulation_schema
"""

from pathlib import Path

import yaml

from src.simulation_schema import OBJECT_TYPES, PROPERTY_TYPES, VOCABULARIES


def document():
    result = {
        "id": "https://github.com/nanotech-empa/aiidalab-openbis/simulation-schema",
        "name": "aiidalab_simulation_objects",
        "description": "Modern simulation objects. Generated from src/simulation_schema.py.",
        "prefixes": {"linkml": "https://w3id.org/linkml/"},
        "imports": ["linkml:types"],
        "default_range": "string",
        "enums": {
            code: {
                "permissible_values": {
                    term: {"description": label} for term, label in terms
                }
            }
            for code, terms in VOCABULARIES.items()
        },
        "slots": {},
        "classes": {},
    }
    used = {
        item["code"] for obj in OBJECT_TYPES.values() for item in obj["assignments"]
    }
    for code in sorted(used):
        prop = PROPERTY_TYPES[code]
        result["slots"][code.lower()] = {
            "title": prop["label"],
            "description": prop["description"],
            "range": prop.get("vocabulary")
            or {"REAL": "float", "INTEGER": "integer", "BOOLEAN": "boolean"}.get(
                prop["dataType"], "string"
            ),
            "multivalued": bool(prop.get("multiValue", False)),
            "annotations": {
                "openbis_code": code,
                "openbis_type": prop["dataType"],
                **(
                    {"openbis_sample_type": prop["sampleType"]}
                    if prop.get("sampleType")
                    else {}
                ),
            },
        }
    for code, obj in OBJECT_TYPES.items():
        result["classes"][code] = {
            "description": obj["description"],
            "annotations": {"openbis_prefix": obj["prefix"]},
            "slots": [item["code"].lower() for item in obj["assignments"]],
            "slot_usage": {
                item["code"].lower(): {
                    "required": item["mandatory"],
                    "annotations": {
                        "openbis_section": item["section"],
                        "openbis_ordinal": ordinal,
                    },
                }
                for ordinal, item in enumerate(obj["assignments"], 1)
            },
        }
    return result


class _ProjectDumper(yaml.SafeDumper):
    """Match the repository's yamlfmt indentation for sequence items."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def serialize_document():
    return (
        "---\n# Generated by python -m schema.generate_simulation_schema; do not edit.\n"
        + yaml.dump(
            document(),
            Dumper=_ProjectDumper,
            indent=4,
            width=4096,
            sort_keys=False,
            allow_unicode=True,
        )
    )


if __name__ == "__main__":
    Path(__file__).with_name("simulation_objects_schema.yaml").write_text(
        serialize_document()
    )
